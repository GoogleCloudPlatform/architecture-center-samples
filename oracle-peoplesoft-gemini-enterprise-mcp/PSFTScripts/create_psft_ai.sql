-- 5. Create PeopleSoft Session Context & Inventory Reservation Extension Tables
DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM all_tables WHERE owner = 'SYSADM' AND table_name = 'PS_GOV_MCP_SESSION_CTX';
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE SYSADM.PS_GOV_MCP_SESSION_CTX (
        SESSION_KEY VARCHAR2(100) PRIMARY KEY,
        OPRID VARCHAR2(30) NOT NULL,
        OPRDEFNDESC VARCHAR2(120),
        EMAILID VARCHAR2(120),
        EMPLID VARCHAR2(20),
        BUSINESS_UNIT VARCHAR2(10) DEFAULT ''US001'',
        SETID VARCHAR2(10) DEFAULT ''SHARE'',
        ROLENAME VARCHAR2(60) DEFAULT ''PeopleSoft Administrator'',
        INITIALIZED_DTTM TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP
      )';
  END IF;

  SELECT COUNT(*) INTO v_cnt FROM all_tables WHERE owner = 'SYSADM' AND table_name = 'PS_GOV_INV_RESERVATIONS';
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE SYSADM.PS_GOV_INV_RESERVATIONS (
        RESERVATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 90001 INCREMENT BY 1) PRIMARY KEY,
        BUSINESS_UNIT VARCHAR2(10) DEFAULT ''US001'' NOT NULL,
        INV_ITEM_ID VARCHAR2(40) NOT NULL,
        STORAGE_AREA VARCHAR2(20) DEFAULT ''AREA1'',
        QTY_RESERVED NUMBER(15,4) NOT NULL,
        OPRID VARCHAR2(30) DEFAULT ''VP1'',
        STATUS VARCHAR2(20) DEFAULT ''ACTIVE'',
        CREATED_DTTM TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP
      )';
  END IF;

  SELECT COUNT(*) INTO v_cnt FROM all_tables WHERE owner = 'SYSADM' AND table_name = 'PS_GOV_INV_BALANCES';
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE SYSADM.PS_GOV_INV_BALANCES (
        BUSINESS_UNIT VARCHAR2(10) NOT NULL,
        INV_ITEM_ID VARCHAR2(40) NOT NULL,
        STORAGE_AREA VARCHAR2(20) DEFAULT ''AREA1'' NOT NULL,
        QTY_ONHAND NUMBER(15,4) DEFAULT 0 NOT NULL,
        QTY_RESERVED NUMBER(15,4) DEFAULT 0 NOT NULL,
        QTY_AVAILABLE NUMBER(15,4) DEFAULT 0 NOT NULL,
        LAST_UPDATED_DTTM TIMESTAMP(6) DEFAULT SYSTIMESTAMP,
        CONSTRAINT PK_PS_GOV_INV_BALANCES PRIMARY KEY (BUSINESS_UNIT, INV_ITEM_ID, STORAGE_AREA)
      )';
    EXECUTE IMMEDIATE '
      INSERT INTO SYSADM.PS_GOV_INV_BALANCES (BUSINESS_UNIT, INV_ITEM_ID, STORAGE_AREA, QTY_ONHAND, QTY_RESERVED, QTY_AVAILABLE)
      SELECT BUSINESS_UNIT, INV_ITEM_ID, ''AREA1'', 100, 0, 100
        FROM (
          SELECT DISTINCT TRIM(BUSINESS_UNIT) AS BUSINESS_UNIT, TRIM(INV_ITEM_ID) AS INV_ITEM_ID
            FROM (
              SELECT BUSINESS_UNIT, INV_ITEM_ID
                FROM SYSADM.PS_BU_ITEMS_INV
               WHERE TRIM(BUSINESS_UNIT) IS NOT NULL
                 AND TRIM(INV_ITEM_ID) IS NOT NULL
                 AND ROWNUM <= 2000
            )
        )
       WHERE ROWNUM <= 500';
    COMMIT;
  END IF;
END;
