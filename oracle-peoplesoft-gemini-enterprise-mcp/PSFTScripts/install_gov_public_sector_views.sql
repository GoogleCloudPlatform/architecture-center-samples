-- 3.1 Views for Skill 3.1 (plain_language_notice_generator)
CREATE OR REPLACE VIEW SYSADM.VW_GOV_CONSTITUENT_NOTICES AS
SELECT
  t.CUSTOMER_TRX_ID AS NOTICE_INTERNAL_ID,
  t.TRX_NUMBER AS NOTICE_ID,
  TO_CHAR(t.TRX_DATE, 'YYYY-MM-DD') AS NOTICE_DATE,
  t.CREATED_FROM AS NOTICE_SCOPE_TYPE,
  t.CT_REFERENCE AS STATUTORY_CITATION,
  t.COMMENTS AS NOTICE_SUMMARY,
  d.DOCUMENT_ID,
  dtl.FILE_NAME AS ATTACHMENT_FILE_NAME,
  dtl.DESCRIPTION AS ATTACHMENT_TITLE,
  lt.LONG_TEXT AS STATUTORY_NOTICE_TEXT
FROM SYSADM.PS_GOV_RA_CUSTOMER_TRX t
LEFT JOIN SYSADM.PS_GOV_FND_ATTACHED_DOCS ad
  ON ad.ENTITY_NAME = 'RA_CUSTOMER_TRX' AND ad.PK1_VALUE = TO_CHAR(t.CUSTOMER_TRX_ID)
LEFT JOIN SYSADM.PS_GOV_FND_DOCUMENTS d
  ON d.DOCUMENT_ID = ad.DOCUMENT_ID
LEFT JOIN SYSADM.PS_GOV_FND_DOCUMENTS_TL dtl
  ON dtl.DOCUMENT_ID = d.DOCUMENT_ID AND dtl.LANGUAGE = 'US'
LEFT JOIN SYSADM.PS_GOV_FND_DOCS_LONG_TEXT lt
  ON lt.MEDIA_ID = d.MEDIA_ID
WHERE t.CUSTOMER_TRX_ID BETWEEN 990001 AND 990999;

-- 3.2 Views for Skill 3.2 (Redaction_and_foia_compliance)
CREATE OR REPLACE VIEW SYSADM.VW_GOV_FOIA_RECORDS AS
SELECT
  CASE WHEN p.PERSON_ID = 990302 THEN 'FOIA-2026-0891' ELSE 'FOIA-2026-0412' END AS FOIA_REQUEST_ID,
  'RFP-2024-HEALTH' AS SOLICITATION_OR_CASE_REF,
  p.PERSON_ID,
  p.EMPLOYEE_NUMBER,
  p.FULL_NAME AS EMPLOYEE_NAME,
  p.NATIONAL_IDENTIFIER AS RAW_SSN,
  TO_CHAR(p.DATE_OF_BIRTH, 'YYYY-MM-DD') AS RAW_DOB,
  p.EMAIL_ADDRESS AS OFFICIAL_EMAIL,
  po.SEGMENT1 AS RELATED_PO_NUMBER,
  po.COMMENTS AS RELATED_CONTRACT_SUMMARY,
  d.DOCUMENT_ID,
  dtl.FILE_NAME,
  dtl.DESCRIPTION AS DOCUMENT_TITLE,
  lt.LONG_TEXT AS FULL_DOCUMENT_CONTENT
FROM SYSADM.PS_GOV_PER_PEOPLE_F p
LEFT JOIN SYSADM.PS_GOV_PO_HEADERS po ON po.PO_HEADER_ID = 990702
LEFT JOIN SYSADM.PS_GOV_FND_ATTACHED_DOCS ad ON ad.ENTITY_NAME = 'PER_PEOPLE_F' AND ad.PK1_VALUE = TO_CHAR(p.PERSON_ID)
LEFT JOIN SYSADM.PS_GOV_FND_DOCUMENTS d ON d.DOCUMENT_ID = ad.DOCUMENT_ID
LEFT JOIN SYSADM.PS_GOV_FND_DOCUMENTS_TL dtl ON dtl.DOCUMENT_ID = d.DOCUMENT_ID AND dtl.LANGUAGE = 'US'
LEFT JOIN SYSADM.PS_GOV_FND_DOCS_LONG_TEXT lt ON lt.MEDIA_ID = d.MEDIA_ID
WHERE p.PERSON_ID BETWEEN 990001 AND 990999;

-- 3.3 Views for Skill 3.3 (Policy_and_statute_assistant)
