-- 3.6 Views for Skill 3.6 (expense_auditor)
CREATE OR REPLACE VIEW SYSADM.VW_GOV_EXPENSE_REPORTS AS
SELECT
  eh.REPORT_HEADER_ID,
  eh.INVOICE_NUM AS EXPENSE_REPORT_NUMBER,
  TO_CHAR(eh.WEEK_END_DATE, 'YYYY-MM-DD') AS REPORT_DATE,
  eh.DESCRIPTION AS REPORT_SUMMARY_AND_AWARD,
  eh.TOTAL AS REPORT_TOTAL_CLAIMED_USD,
  NVL(eh.EXPENSE_STATUS_CODE, 'PENDMGR') AS EXPENSE_STATUS_CODE,
  el.REPORT_LINE_ID,
  el.DISTRIBUTION_LINE_NUMBER AS LINE_NUM,
  el.ITEM_DESCRIPTION AS EXPENSE_LINE_DESCRIPTION,
  el.AMOUNT AS LINE_CLAIMED_AMOUNT_USD,
  el.JUSTIFICATION AS REGULATORY_AUDIT_NOTE,
  lt.LONG_TEXT AS ATTACHED_FOLIO_OCR_TRANSCRIPT
FROM SYSADM.PS_GOV_EX_REPORT_HDRS eh
LEFT JOIN SYSADM.PS_GOV_EX_REPORT_LINES el ON el.REPORT_HEADER_ID = eh.REPORT_HEADER_ID
LEFT JOIN SYSADM.PS_GOV_FND_ATTACHED_DOCS ad
  ON ad.ENTITY_NAME IN ('AP_EXPENSE_REPORT_HEADERS', 'OIE_HEADER_ATTACHMENTS')
  AND ad.PK1_VALUE = TO_CHAR(eh.REPORT_HEADER_ID)
LEFT JOIN SYSADM.PS_GOV_FND_DOCUMENTS d ON d.DOCUMENT_ID = ad.DOCUMENT_ID
LEFT JOIN SYSADM.PS_GOV_FND_DOCS_LONG_TEXT lt ON lt.MEDIA_ID = d.MEDIA_ID
WHERE eh.INVOICE_NUM LIKE 'EXP-ATL-9921%'
   OR eh.INVOICE_NUM LIKE 'EXP-DEN-5521%'
   OR eh.INVOICE_NUM LIKE 'EXP-CHI-8812%';

CREATE OR REPLACE VIEW SYSADM.VW_GOV_PO_INVOICE_MATCH AS
SELECT
  ai.INVOICE_ID,
  ai.INVOICE_NUM,
  TO_CHAR(ai.INVOICE_DATE, 'YYYY-MM-DD') AS INVOICE_DATE,
  ai.INVOICE_AMOUNT AS INVOICE_TOTAL_USD,
  ai.DESCRIPTION AS INVOICE_AND_GRANT_LINE_DETAILS,
  po.PO_HEADER_ID,
  po.SEGMENT1 AS MATCHED_PO_NUMBER,
  po.AUTHORIZATION_STATUS AS PO_STATUS,
  po.COMMENTS AS PO_PROCUREMENT_METHOD_NOTES,
  ga.AWARD_NUMBER AS FEDERAL_GRANT_AWARD_ID,
  ga.AWARD_FULL_NAME AS FEDERAL_GRANT_TITLE,
  TO_CHAR(ga.START_DATE_ACTIVE, 'YYYY-MM-DD') AS GRANT_POP_START,
  TO_CHAR(ga.END_DATE_ACTIVE, 'YYYY-MM-DD') AS GRANT_POP_END
FROM SYSADM.PS_GOV_AP_INVOICES ai
LEFT JOIN SYSADM.PS_GOV_PO_HEADERS po
  ON (
    (ai.INVOICE_NUM LIKE 'MS-1049%' AND po.SEGMENT1 = 'PO-7801') OR
    (ai.INVOICE_NUM LIKE 'EPA-SPEC-68400%' AND po.SEGMENT1 = 'PO-7802')
  )
LEFT JOIN SYSADM.PS_GOV_GMS_AWARDS ga
  ON (
    (ai.INVOICE_NUM LIKE 'HM-4409%' AND ga.AWARD_ID = 990003) OR
    (ai.INVOICE_NUM LIKE 'V-2026-301%' AND ga.AWARD_ID = 990004) OR
    (ai.INVOICE_NUM LIKE 'MS-1049%' AND ga.AWARD_ID = 990005) OR
    (ai.INVOICE_NUM LIKE 'INV-2026-8841%' AND ga.AWARD_ID = 990006) OR
    (ai.INVOICE_NUM LIKE 'NAPA-1840%' AND ga.AWARD_ID = 990002) OR
    (ai.INVOICE_NUM LIKE 'EPA-SPEC-68400%' AND ga.AWARD_ID = 990007)
  )
WHERE ai.INVOICE_NUM LIKE 'HM-4409%'
   OR ai.INVOICE_NUM LIKE 'V-2026-301%'
   OR ai.INVOICE_NUM LIKE 'MS-1049%'
   OR ai.INVOICE_NUM LIKE 'INV-2026-8841%'
   OR ai.INVOICE_NUM LIKE 'NAPA-1840%'
   OR ai.INVOICE_NUM LIKE 'EPA-SPEC-68400%';

