-- 1. Create JDE Julian Date (CYYDDD) <-> Oracle DATE Helper Functions
CREATE OR REPLACE FUNCTION PRODDTA.JDE_TO_DATE(p_julian IN NUMBER)
RETURN DATE DETERMINISTIC IS
  v_year NUMBER;
  v_ddd  NUMBER;
BEGIN
  IF p_julian IS NULL OR p_julian <= 0 THEN
    RETURN NULL;
  END IF;
  v_year := 1900 + TRUNC(p_julian / 1000);
  v_ddd  := MOD(p_julian, 1000);
  RETURN TO_DATE(TO_CHAR(v_year, 'FM0000') || '-' || TO_CHAR(v_ddd, 'FM000'), 'YYYY-DDD');
EXCEPTION
  WHEN OTHERS THEN
    RETURN NULL;
END;
/

CREATE OR REPLACE FUNCTION PRODDTA.DATE_TO_JDE(p_date IN DATE)
RETURN NUMBER DETERMINISTIC IS
BEGIN
  IF p_date IS NULL THEN
    RETURN 0;
  END IF;
  RETURN (TO_NUMBER(TO_CHAR(p_date, 'YYYY')) - 1900) * 1000
       + TO_NUMBER(TO_CHAR(p_date, 'DDD'));
END;
/

